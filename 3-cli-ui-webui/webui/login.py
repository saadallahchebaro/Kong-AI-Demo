#!/usr/bin/env python3
"""Write .login.js: a persona picker on GNB Assist's sign-in page. Pick a name and the test account's email and password fill in
(the password stays masked), then Sign in. A demo convenience on the local laptop only.
Open WebUI loads /static/loader.js on every page; docker-compose.yml mounts .login.js there. up.sh runs this before starting.
The file holds the test passwords from .personas.env, so it's git-ignored like them. Never open it on the shared screen."""
import ast, json, pathlib

HERE = pathlib.Path(__file__).resolve().parent
env = dict(l.split("=", 1) for l in (HERE / ".personas.env").read_text().splitlines() if "=" in l and not l.startswith("#"))
# the personas as setup.py defines them (email, name, password var, group), so the two never drift
tree = ast.parse((HERE / "setup.py").read_text())
PERSONAS = next(ast.literal_eval(n.value) for n in tree.body if isinstance(n, ast.Assign) and getattr(n.targets[0], "id", "") == "PERSONAS")
people = [{"first": name.split(" (")[0], "team": group, "email": email, "pw": env[pw]} for email, name, pw, group in PERSONAS]
people.append({"first": "Platform team", "team": "admin", "email": env["WEBUI_ADMIN_EMAIL"], "pw": env["WEBUI_ADMIN_PASSWORD"]})

JS = """// GNB Assist sign-in: pick a persona and its test credentials fill in. Generated by webui/login.py; local demo only, git-ignored.
(() => {
  const P = %s;
  const css = `
#gnb-picker { margin: 18px 0 4px; }
#gnb-picker .t { font-size: 12px; letter-spacing: .06em; text-transform: uppercase; color: #5B6B63; margin: 0 0 8px; text-align: center; }
#gnb-picker .g { display: grid; grid-template-columns: repeat(3, 1fr); gap: 8px; }
#gnb-picker button { border: 1px solid #D5E0D9; background: #fff; border-radius: 12px; padding: 8px 6px; cursor: pointer; text-align: center; line-height: 1.2; }
#gnb-picker button:hover { border-color: #0F5A44; }
#gnb-picker button b { display: block; font-size: 14px; color: #08372A; }
#gnb-picker button span { display: block; font-size: 11px; color: #5B6B63; margin-top: 2px; }
#gnb-picker button.on { background: #0F5A44; border-color: #0F5A44; box-shadow: 0 0 0 3px rgba(200, 162, 74, .45); }
#gnb-picker button.on b, #gnb-picker button.on span { color: #fff; }
#gnb-picker button.admin { opacity: .75; }`;
  const setValue = (id, v) => {
    const e = document.getElementById(id); if (!e) return;
    Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, "value").set.call(e, v);
    e.dispatchEvent(new Event("input", { bubbles: true }));  // so the page's own form state sees it
  };
  function mount() {
    if (!location.pathname.startsWith("/auth") || document.getElementById("gnb-picker")) return;
    const form = document.getElementById("password")?.closest("form"); if (!form) return;
    if (!document.getElementById("gnb-picker-css")) { const s = document.createElement("style"); s.id = "gnb-picker-css"; s.textContent = css; document.head.append(s); }
    const box = document.createElement("div"); box.id = "gnb-picker";
    box.innerHTML = '<div class="t">Sign in as</div><div class="g">' + P.map((p, i) =>
      `<button type="button" data-i="${i}" class="${p.team === "admin" ? "admin" : ""}"><b>${p.first}</b><span>${p.team}</span></button>`).join("") + "</div>";
    box.addEventListener("click", ev => {
      const b = ev.target.closest("button[data-i]"); if (!b) return;
      box.querySelectorAll("button").forEach(x => x.classList.toggle("on", x === b));
      const p = P[b.dataset.i]; setValue("email", p.email); setValue("password", p.pw);
      form.querySelector('button[type="submit"]')?.focus();
    });
    const fields = [...form.children].find(c => c.contains(document.getElementById("email"))) || form.firstChild;
    form.insertBefore(box, fields);  // under the title, above Email
  }
  new MutationObserver(mount).observe(document.documentElement, { childList: true, subtree: true }); mount();
})();
""" % json.dumps(people)

out = HERE / ".login.js"
out.write_text(JS)
print(f"sign-in picker: {len(people)} accounts (values not shown) → {out.name}")
